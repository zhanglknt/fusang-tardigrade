def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def put_file(src, dst_rel, category):
    """Copy one file into the staging tree and record it."""
    dst = os.path.join(TMP, dst_rel.replace("/", os.sep))
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copy2(src, dst)
    added.append((dst_rel, sha256(dst), category))
    return dst


def put_tree(src_dir, dst_rel, category, skip_dirs=()):
    """Copy a whole directory (files only, honouring skip_dirs) and record each file."""
    n = 0
    for dirpath, dirnames, filenames in os.walk(src_dir):
        dirnames[:] = [d for d in dirnames if d not in skip_dirs]
        for fn in sorted(filenames):
            src = os.path.join(dirpath, fn)
            rel = os.path.relpath(src, src_dir).replace(os.sep, "/")
            put_file(src, f"{dst_rel}/{rel}", category)
            n += 1
    return n


def prepend(path, header):
    with open(path, "r", encoding="utf-8") as fh:
        body = fh.read()
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(header + "\n" + body)


def sub(path, old, new, required=True):
    """In-place literal text replacement inside the staging tree."""
    with open(path, "r", encoding="utf-8") as fh:
        t = fh.read()
    if old not in t:
        if required:
            raise SystemExit(f"PATTERN NOT FOUND in {path}:\n{old[:200]}")
        return False
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(t.replace(old, new))
    return True


